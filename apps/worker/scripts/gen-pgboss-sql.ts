/**
 * Generates the pg-boss schema migration for the INSTALLED pg-boss version, so the worker can run with
 * `migrate: false` (no DDL at runtime). Usage: pnpm --filter @outreach/worker gen:pgboss-sql [outfile]
 * Then apply the file with the Supabase MCP apply_migration and save it under supabase/migrations/.
 */
import { writeFileSync } from "node:fs";
import PgBoss from "pg-boss";

export const QUEUES = [
  { name: "lead-pipeline-dead", options: { policy: "standard", retentionMinutes: 43200 } },
  {
    name: "lead-pipeline",
    options: {
      policy: "short",
      retryLimit: 3,
      retryDelay: 30,
      retryBackoff: true,
      expireInSeconds: 900,
      retentionMinutes: 10080,
      deadLetter: "lead-pipeline-dead",
    },
  },
  {
    name: "queue-smoke",
    options: { policy: "short", retryLimit: 1, retryDelay: 1, retryBackoff: false, expireInSeconds: 60, retentionMinutes: 60 },
  },
];

export function buildPgbossSql(): string {
  const plan = PgBoss.getConstructionPlans("pgboss");
  const start = plan.indexOf("CREATE SCHEMA");
  const end = plan.lastIndexOf("COMMIT;");
  if (start < 0 || end < 0) throw new Error("unexpected pg-boss construction plan format; review the installed version");
  const body = plan.slice(start, end).trim();
  const queues = QUEUES.map((q) => `select pgboss.create_queue('${q.name}', '${JSON.stringify(q.options)}');`).join("\n");
  const tables = ["version", "queue", "schedule", "subscription", "job", "archive"];
  return [
    "-- Phase 4: pg-boss schema, generated by apps/worker/scripts/gen-pgboss-sql.ts from the pinned pg-boss version.",
    "-- The worker runs with migrate:false, so it never executes DDL. Queues are created here, not at runtime.",
    "-- The schema is not exposed to PostgREST; privileges are revoked and RLS is on as belt and braces.",
    "",
    body,
    "",
    queues,
    "",
    "revoke all on schema pgboss from public, anon, authenticated;",
    "revoke all on all tables in schema pgboss from public, anon, authenticated;",
    "revoke all on all functions in schema pgboss from public, anon, authenticated;",
    ...tables.map((t) => `alter table pgboss.${t} enable row level security;`),
    "do $$ declare r record; begin",
    "  for r in select partition_name from pgboss.queue loop",
    "    execute format('alter table pgboss.%I enable row level security', r.partition_name);",
    "    execute format('revoke all on pgboss.%I from public, anon, authenticated', r.partition_name);",
    "  end loop;",
    "end $$;",
    "",
  ].join("\n");
}

const isMain = process.argv[1]?.replace(/\\/g, "/").endsWith("gen-pgboss-sql.ts");
if (isMain) {
  const out = process.argv[2];
  const sql = buildPgbossSql();
  if (out) writeFileSync(out, sql);
  else process.stdout.write(sql);
}
